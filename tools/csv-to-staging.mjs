/**
 * csv-to-staging.mjs — turn the exported Google Sheet tabs into a loadable
 * staging script.
 *
 * Usage:
 *   1. export each tab of `Tryento_App_Data` as CSV into migration/csv/
 *      (the filename becomes the staging table name)
 *   2. node tools/csv-to-staging.mjs
 *   3. run migration/generated/01_staging_load.sql in the Supabase SQL editor
 *
 * Design rules, both non-negotiable:
 *
 *  - EVERY COLUMN LANDS AS text. Letting Postgres infer types on import is how
 *    "1,5" becomes 15, how a blank date becomes 1970, and how the whole thing
 *    fails on row 4,000 with half the data already in. Typing happens in the
 *    transform step, explicitly, where a bad value can be quarantined instead
 *    of silently coerced.
 *
 *  - THE STAGING TABLES ARE KEPT FOREVER. They are the audit trail: when
 *    someone asks in eight months why a tray shows 410 g, the answer has to be
 *    traceable back to the original sheet row, by number.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSV_DIR = path.join(ROOT, 'migration', 'csv');
const OUT_DIR = path.join(ROOT, 'migration', 'generated');

/** RFC-4180 CSV: handles quoted fields, embedded commas, newlines and "". */
export function parseCsv(text) {
  const rows = [];
  let row = [], field = '', inQuotes = false;
  const s = text.replace(/^﻿/, '');       // strip BOM

  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (inQuotes) {
      if (c === '"') {
        if (s[i + 1] === '"') { field += '"'; i++; }
        else inQuotes = false;
      } else field += c;
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field); field = '';
    } else if (c === '\r') {
      // handled by \n
    } else if (c === '\n') {
      row.push(field); field = '';
      rows.push(row); row = [];
    } else {
      field += c;
    }
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.some(v => v !== ''));
}

/** "ID Bandeja" / "Peso Final Kg" -> id_bandeja / peso_final_kg */
export function normalizeHeader(h) {
  return String(h)
    .normalize('NFD').replace(/[̀-ͯ]/g, '')   // strip accents
    .replace(/[^\w\s]/g, ' ')
    .trim()
    .replace(/\s+/g, '_')
    .toLowerCase()
    .replace(/^_+|_+$/g, '') || 'col';
}

export function normalizeTable(filename) {
  return 'staging.' + normalizeHeader(path.basename(filename, '.csv'));
}

const q = v => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

async function main() {
  let files;
  try {
    files = (await readdir(CSV_DIR)).filter(f => f.toLowerCase().endsWith('.csv')).sort();
  } catch {
    console.error(`No existe ${path.relative(ROOT, CSV_DIR)}.`);
    console.error('Exporta cada pestaña de Tryento_App_Data como CSV allí y vuelve a correr.');
    process.exitCode = 1;
    return;
  }
  if (!files.length) {
    console.error(`No hay CSVs en ${path.relative(ROOT, CSV_DIR)}.`);
    process.exitCode = 1;
    return;
  }

  await mkdir(OUT_DIR, { recursive: true });

  const out = [
    '-- GENERATED by tools/csv-to-staging.mjs — do not edit by hand.',
    '-- Every column is text on purpose; see the header of that script.',
    '',
    'create schema if not exists staging;',
    ''
  ];
  const summary = [];

  for (const file of files) {
    const rows = parseCsv(await readFile(path.join(CSV_DIR, file), 'utf8'));
    if (!rows.length) { console.warn(`  skip  ${file} (vacío)`); continue; }

    const table = normalizeTable(file);
    const headers = rows[0].map(normalizeHeader);

    // Deduplicate repeated headers (Sheets allows them; Postgres does not).
    const seen = new Map();
    const cols = headers.map(h => {
      const n = (seen.get(h) || 0) + 1;
      seen.set(h, n);
      return n === 1 ? h : `${h}_${n}`;
    });

    const body = rows.slice(1);
    out.push(`-- ── ${file} → ${table} (${body.length} filas) ──`);
    out.push(`drop table if exists ${table} cascade;`);
    out.push(`create table ${table} (`);
    out.push(`  fila_origen int,`);
    out.push(`  importado_at timestamptz not null default now(),`);
    out.push(cols.map(c => `  ${JSON.stringify(c)} text`).join(',\n'));
    out.push(');');

    if (body.length) {
      const CHUNK = 500;
      for (let i = 0; i < body.length; i += CHUNK) {
        const slice = body.slice(i, i + CHUNK);
        out.push(`insert into ${table} (fila_origen, ${cols.map(c => JSON.stringify(c)).join(', ')}) values`);
        out.push(slice.map((r, j) => {
          // +2: the sheet's row 1 is the header, and rows are 1-indexed, so
          // fila_origen matches what you see in the spreadsheet.
          const vals = cols.map((_, k) => q(r[k] === '' ? null : r[k]));
          return `  (${i + j + 2}, ${vals.join(', ')})`;
        }).join(',\n') + ';');
      }
    }
    out.push('');
    summary.push({ file, table, rows: body.length, cols: cols.length });
  }

  const target = path.join(OUT_DIR, '01_staging_load.sql');
  await writeFile(target, out.join('\n'), 'utf8');

  console.log('Staging generado:');
  for (const s of summary) console.log(`  ${s.table.padEnd(34)} ${String(s.rows).padStart(6)} filas, ${s.cols} columnas`);
  console.log(`\n  -> ${path.relative(ROOT, target)}`);
  console.log('\nSiguiente: revisa los nombres de columna generados contra migration/02_transform.sql');
  console.log('antes de correrlo — los encabezados de la hoja pueden no coincidir con lo esperado.');
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('csv-to-staging.mjs')) {
  main().catch(e => { console.error(e); process.exitCode = 1; });
}
